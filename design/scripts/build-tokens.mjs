#!/usr/bin/env node
// Boona token build. tokens.json is the only input. Run: node design/scripts/build-tokens.mjs
// Emits: design/build/tokens.css, design/build/tailwind.tokens.json, tailwind.config.ts (root), design/build/figma-variables.json
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));
const outDir = resolve(root, "design/build");
mkdirSync(outDir, { recursive: true });

const MODES = tokens.$extensions.boona.modes;

// ---------- resolve ----------
const getPath = (path) => path.split(".").reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), tokens);
const isToken = (n) => n && typeof n === "object" && "$value" in n;
const isAlias = (v) => typeof v === "string" && /^\{[^}]+\}$/.test(v);

function rawValue(token, mode) {
  const dark = token.$extensions?.boona?.dark;
  return mode === "dark" && dark !== undefined ? dark : token.$value;
}
function resolveValue(v, mode, depth = 0) {
  if (depth > 20) throw new Error("Alias loop: " + v);
  if (isAlias(v)) {
    const t = getPath(v.slice(1, -1));
    if (!isToken(t)) throw new Error("Unknown alias " + v);
    return resolveValue(rawValue(t, mode), mode, depth + 1);
  }
  if (Array.isArray(v)) return v.map((x) => resolveValue(x, mode, depth + 1));
  if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolveValue(x, mode, depth + 1)]));
  return v;
}
// flat list of {path:[...], token}
function walk(node, path = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (isToken(v)) out.push({ path: [...path, k], token: v });
    else if (v && typeof v === "object") walk(v, [...path, k], out);
  }
  return out;
}
const all = walk(tokens).filter((t) => t.path[0] !== "color" || t.path[1] !== "primitive"); // primitives stay internal
const byGroup = (g) => all.filter((t) => t.path[0] === g);
const varName = (p) => "--" + p.join("-").replace(/[^a-z0-9-]/gi, "-").toLowerCase();
const fontStack = (arr) => arr.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
const shadow = (v) => (v === "none" ? "none" : `${v.offsetX} ${v.offsetY} ${v.blur} ${v.spread} ${v.color}`);
const bezier = (a) => `cubic-bezier(${a.join(", ")})`;

function cssValue(t, mode) {
  const v = resolveValue(rawValue(t.token, mode), mode);
  switch (t.token.$type) {
    case "fontFamily": return fontStack(v);
    case "shadow": return shadow(v);
    case "cubicBezier": return bezier(v);
    case "typography": return null; // expanded separately
    default: return String(v);
  }
}

// ---------- contrast gate (WCAG 2.2 AA) ----------
const lum = (hex) => {
  const h = hex.replace("#", "").slice(0, 6);
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)]; return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
const colourOf = (path, mode) => { const t = getPath(path); return resolveValue(rawValue(t, mode), mode); };
// [foreground, background, minimum]. 4.5 = body text, 3 = large text (24px+ or 19px bold), icons and the accent square.
const PAIRS = [
  ["color.ink", "color.ground", 4.5], ["color.ink", "color.surface", 4.5], ["color.quiet", "color.ground", 4.5], ["color.quiet", "color.surface", 4.5],
  ["color.on-ink", "color.ink", 4.5], ["color.link", "color.ground", 4.5], ["color.focus", "color.ground", 3], ["color.error", "color.ground", 4.5], ["color.success", "color.ground", 4.5],
  ["color.on-bar", "color.bar", 4.5], ["color.quiet-on-bar", "color.bar", 4.5], ["color.proof", "color.bar", 4.5], ["color.warning-outage", "color.bar", 3], ["color.warning-outage-ink", "color.ground", 4.5],
  ["product.azhagi.accent", "color.bar", 3], ["product.azhagi.ink", "color.ground", 4.5], ["product.cue.accent", "color.bar", 3], ["product.cue.ink", "color.ground", 4.5], ["product.automation.accent", "color.bar", 3], ["product.automation.ink", "color.ground", 4.5],
];
const report = ["| pair | light | dark | min |", "|---|---|---|---|"];
let failures = 0;
for (const [fg, bg, min] of PAIRS) {
  const rs = MODES.map((m) => ratio(colourOf(fg, m), colourOf(bg, m)));
  const ok = rs.every((r) => r >= min);
  if (!ok) failures++;
  report.push(`| ${fg} on ${bg} | ${rs[0].toFixed(2)} | ${rs[1].toFixed(2)} | ${min} ${ok ? "" : "FAIL"} |`);
}
writeFileSync(resolve(outDir, "contrast-report.md"), `# Contrast report\n\nGenerated by build-tokens.mjs. Every pair must meet its minimum in both modes or the build fails.\n\n${report.join("\n")}\n`);
if (failures) { console.error(`Contrast gate failed for ${failures} pair(s). See design/build/contrast-report.md`); process.exit(1); }

// ---------- tokens.css ----------
let css = `/* Generated from design/tokens.json by design/scripts/build-tokens.mjs. Do not edit. */\n\n`;
const modeBlock = (mode) => {
  const lines = [];
  for (const t of all) {
    if (t.token.$type === "typography") {
      const v = resolveValue(rawValue(t.token, mode), mode);
      const n = varName(t.path);
      lines.push(`${n}-font-family: ${fontStack(v.fontFamily)};`, `${n}-font-size: ${v.fontSize};`, `${n}-font-weight: ${v.fontWeight};`, `${n}-line-height: ${v.lineHeight};`, `${n}-letter-spacing: ${v.letterSpacing};`);
    } else {
      lines.push(`${varName(t.path)}: ${cssValue(t, mode)};`);
    }
  }
  return lines.map((l) => "  " + l).join("\n");
};
const colourOnly = (mode) =>
  all.filter((t) => t.token.$type === "color").map((t) => `  ${varName(t.path)}: ${cssValue(t, mode)};`).join("\n");

css += `:root {\n  color-scheme: light dark;\n${modeBlock("light")}\n}\n\n`;
css += `/* Dark: follows the system unless data-theme is set explicitly. */\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${colourOnly("dark")}\n  }\n}\n`;
css += `:root[data-theme="dark"] {\n${colourOnly("dark")}\n}\n\n`;

css += `/* Base rules the tokens imply */\n`;
css += `html { background: var(--color-ground); color: var(--color-ink); font-family: var(--font-family-sans); -webkit-font-smoothing: antialiased; text-rendering: optimizeLegibility; }\n`;
css += `body { margin: 0; font-size: var(--text-body-font-size); line-height: var(--text-body-line-height); }\n`;
css += `::selection { background: var(--color-selection); }\n`;
css += `a { color: var(--color-link); text-decoration: underline; text-underline-offset: 0.2em; text-decoration-thickness: 1px; }\n`;
css += `:focus-visible { outline: var(--border-heavy) solid var(--color-focus); outline-offset: var(--border-focus-offset); }\n`;
css += `.tnum, .readout, table, [data-number] { font-variant-numeric: var(--font-feature-numbers); }\n`;
css += `.measure { max-width: var(--size-measure); }\n`;
css += `@media (prefers-reduced-motion: reduce) { *, *::before, *::after { animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; scroll-behavior: auto !important; } }\n`;
css += `@media (max-width: 639px) { :root { --text-hero-font-size: var(--font-size-40); --text-display-font-size: var(--font-size-40); --text-h1-font-size: var(--font-size-30); --size-gutter: 20px; } }\n`;
css += `@media (min-width: 1024px) { :root { --size-gutter: 56px; } }\n\n`;

css += `/* Text style classes (same names as Figma text styles) */\n`;
for (const t of byGroup("text")) {
  const n = varName(t.path);
  css += `.${t.path.join("-")} { font-family: var(${n}-font-family); font-size: var(${n}-font-size); font-weight: var(${n}-font-weight); line-height: var(${n}-line-height); letter-spacing: var(${n}-letter-spacing); }\n`;
}
writeFileSync(resolve(outDir, "tokens.css"), css);

// ---------- tailwind ----------
const tw = { colors: {}, fontFamily: {}, fontSize: {}, fontWeight: {}, spacing: {}, borderRadius: {}, borderWidth: {}, outlineWidth: {}, outlineOffset: {}, boxShadow: {}, zIndex: {}, transitionDuration: {}, transitionTimingFunction: {}, screens: {}, maxWidth: {}, height: {}, minHeight: {}, minWidth: {}, width: {} };
const setNested = (obj, keys, val) => { let o = obj; keys.slice(0, -1).forEach((k) => (o = o[k] ??= {})); o[keys.at(-1)] = val; };
for (const t of all) {
  const p = t.path, v = (mode) => resolveValue(rawValue(t.token, mode), mode);
  switch (p[0]) {
    case "color": setNested(tw.colors, p.slice(1), `var(${varName(p)})`); break;
    case "product": setNested(tw.colors, ["product", ...p.slice(1)], `var(${varName(p)})`); break;
    case "font":
      if (p[1] === "family") tw.fontFamily[p[2]] = v("light");
      if (p[1] === "weight") tw.fontWeight[p[2]] = String(v("light"));
      break;
    case "text": { const s = v("light"); tw.fontSize[p[1]] = [s.fontSize, { lineHeight: String(s.lineHeight), letterSpacing: s.letterSpacing, fontWeight: String(s.fontWeight) }]; break; }
    case "space": tw.spacing[p[1]] = v("light"); break;
    case "size": {
      const val = v("light"); tw.height[p[1]] = val; tw.minHeight[p[1]] = val; tw.minWidth[p[1]] = val; tw.width[p[1]] = val;
      if (["container", "measure"].includes(p[1])) tw.maxWidth[p[1]] = val;
      if (p[1] === "gutter") tw.spacing.gutter = `var(${varName(p)})`; // responsive: tokens.css changes the var by breakpoint
      break;
    }
    case "radius": tw.borderRadius[p[1] === "none" ? "none" : p[1]] = v("light"); break;
    case "border": tw.borderWidth[p[1]] = v("light"); tw.outlineWidth[p[1]] = v("light"); tw.outlineOffset[p[1]] = v("light"); break;
    case "elevation": tw.boxShadow[p[1]] = shadow(v("light")); break;
    case "z": tw.zIndex[p[1]] = String(v("light")); break;
    case "motion": if (p[1] === "duration") tw.transitionDuration[p[2]] = v("light"); if (p[1] === "easing") tw.transitionTimingFunction[p[2]] = bezier(v("light")); break;
    case "breakpoint": tw.screens[p[1]] = v("light"); break;
  }
}
tw.borderRadius.DEFAULT = tw.borderRadius.none;
writeFileSync(resolve(outDir, "tailwind.tokens.json"), JSON.stringify(tw, null, 2));

const twConfig = `// Generated from design/tokens.json. Do not edit by hand; change tokens.json and run design/scripts/build-tokens.mjs.
import type { Config } from "tailwindcss";
import raw from "./design/build/tailwind.tokens.json";

type FontSizeEntry = [string, { lineHeight: string; letterSpacing: string; fontWeight: string }];
const tokens = { ...raw, fontSize: raw.fontSize as unknown as Record<string, FontSizeEntry> };

export default {
  content: ["./src/**/*.{ts,tsx,html,mdx}"],
  darkMode: ["selector", '[data-theme="dark"]'], // system preference is handled in tokens.css; this selector is the manual override
  theme: {
    screens: tokens.screens,
    fontFamily: tokens.fontFamily,
    extend: {
      colors: tokens.colors,
      fontSize: tokens.fontSize,
      fontWeight: tokens.fontWeight,
      spacing: tokens.spacing,
      borderRadius: tokens.borderRadius,
      borderWidth: tokens.borderWidth,
      outlineWidth: tokens.outlineWidth,
      outlineOffset: tokens.outlineOffset,
      boxShadow: tokens.boxShadow,
      zIndex: tokens.zIndex,
      transitionDuration: tokens.transitionDuration,
      transitionTimingFunction: tokens.transitionTimingFunction,
      maxWidth: tokens.maxWidth,
      height: tokens.height,
      minHeight: tokens.minHeight,
      minWidth: tokens.minWidth,
      width: tokens.width,
    },
  },
  plugins: [],
} satisfies Config;
`;
writeFileSync(resolve(root, "tailwind.config.ts"), twConfig);

// ---------- figma ----------
// One collection "Boona" with modes Light/Dark for colours; a second collection "Boona · scale" (single mode) for numbers and strings.
const hexToRgba = (hex) => {
  const h = hex.replace("#", "");
  const n = h.length === 8 ? h : h.length === 6 ? h + "FF" : h.length === 3 ? [...h].map((c) => c + c).join("") + "FF" : null;
  if (!n) throw new Error("Bad hex " + hex);
  const [r, g, b, a] = [0, 2, 4, 6].map((i) => parseInt(n.slice(i, i + 2), 16) / 255);
  return { r, g, b, a };
};
const figma = {
  generatedFrom: "design/tokens.json",
  version: tokens.$extensions.boona.version,
  collections: [
    { name: "Boona", modes: MODES.map((m) => m[0].toUpperCase() + m.slice(1)), variables: [] },
    { name: "Boona · scale", modes: ["Value"], variables: [] },
  ],
  textStyles: [],
};
for (const t of all) {
  const p = t.path;
  if (t.token.$type === "color") {
    figma.collections[0].variables.push({
      name: p.join("/"), type: "COLOR", description: t.token.$description ?? "", cssVar: `var(${varName(p)})`,
      valuesByMode: Object.fromEntries(MODES.map((m) => [m[0].toUpperCase() + m.slice(1), hexToRgba(resolveValue(rawValue(t.token, m), m))])),
      scopes: p[0] === "product" || ["ground", "surface", "bar"].includes(p[1]) ? ["FRAME_FILL", "SHAPE_FILL", "TEXT_FILL", "STROKE_COLOR"] : ["ALL_SCOPES"],
    });
  } else if (["dimension"].includes(t.token.$type) && ["space", "size", "radius", "border", "font", "breakpoint"].includes(p[0])) {
    const v = resolveValue(t.token.$value, "light");
    const num = parseFloat(v);
    if (Number.isFinite(num) && /px$/.test(v)) figma.collections[1].variables.push({ name: p.join("/"), type: "FLOAT", description: t.token.$description ?? "", cssVar: `var(${varName(p)})`, valuesByMode: { Value: num }, scopes: p[0] === "radius" ? ["CORNER_RADIUS"] : p[0] === "space" ? ["GAP", "WIDTH_HEIGHT"] : p[0] === "font" ? ["FONT_SIZE"] : ["WIDTH_HEIGHT", "GAP"] });
  } else if (t.token.$type === "fontFamily") {
    figma.collections[1].variables.push({ name: p.join("/"), type: "STRING", description: t.token.$description ?? "", cssVar: `var(${varName(p)})`, valuesByMode: { Value: resolveValue(t.token.$value, "light")[0] }, scopes: ["FONT_FAMILY"] });
  } else if (t.token.$type === "fontWeight") {
    figma.collections[1].variables.push({ name: p.join("/"), type: "FLOAT", description: "", cssVar: `var(${varName(p)})`, valuesByMode: { Value: t.token.$value }, scopes: ["FONT_WEIGHT"] });
  } else if (t.token.$type === "typography") {
    const v = resolveValue(t.token.$value, "light");
    figma.textStyles.push({ name: "Boona/" + p.slice(1).join("/"), fontFamily: v.fontFamily[0], fontSize: parseFloat(v.fontSize), fontWeight: v.fontWeight, lineHeightPercent: Math.round(v.lineHeight * 100), letterSpacingPercent: Math.round(parseFloat(v.letterSpacing) * 100), description: t.token.$description ?? "" });
  }
}
writeFileSync(resolve(outDir, "figma-variables.json"), JSON.stringify(figma, null, 2));

console.log(`tokens.css, tailwind.tokens.json, tailwind.config.ts, figma-variables.json written. ${all.length} tokens, ${figma.collections[0].variables.length} colour variables, ${figma.textStyles.length} text styles.`);
